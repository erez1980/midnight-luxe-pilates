// build time (scripts/prerender.mjs). Hebrew only. Copy follows what Rotem
// confirmed for the home page — no prices, no studio address.

export interface LandingSection {
  title: string;
  text?: string;
  points?: string[];
  steps?: { title: string; text: string }[];
}

export interface Landing {
  slug: string;
  title: string; // <title>
  description: string; // meta description
  h1: string;
  eyebrow: string;
  intro: string;
  sections: LandingSection[];
  faq: { q: string; a: string }[];
  cta: { title: string; text: string; label: string; message: string };
  service?: { name: string; description: string };
  // true describes the page's subject as the lesson-builder web app.
  app?: boolean;
  // 'conditions' adds the exercise suitability lists for pregnancy/postnatal.
  // Those lists stay hidden until Rotem approves them (PUBLISH_CONDITION_TABLES).
  extra?: 'conditions';
  // Lists every exercise of this apparatus. The page is a catalog, not a
  // workout plan and not a medical recommendation.
  apparatus?: 'mat' | 'chair' | 'reformer' | 'cadillac' | 'props';
  // Crumb between the home page and this page. `href` is site-relative.
  parent?: { href: string; label: string };
  // Site-relative links (trailing slash, no leading slash).
  related?: { href: string; title: string; text: string }[];
}

